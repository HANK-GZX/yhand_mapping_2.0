import argparse
import csv
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from hand_motor_map import FINGER_MOTOR_IDS_BY_HAND, model_motor_ids


Q_SOURCE_COLS = [f"q_{i}" for i in range(4)]
def thumb_source_columns(hand):
    compact_ids = list(FINGER_MOTOR_IDS_BY_HAND[hand])
    return [f"m_{compact_ids.index(mid)}" for mid in model_motor_ids(hand, "thumb")]


M_SOURCE_COLS = thumb_source_columns("left")
M_TARGET_COLS = [f"m_{i}" for i in range(6)]
META_COLS = ["session_id", "trial_id", "active_finger", "point_id"]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Extract thumb q_4/m_6 training data from preprocessed_raw.csv."
    )
    parser.add_argument("--hand", choices=["left", "right"], default="left")
    parser.add_argument(
        "--input-csv",
        type=str,
        default="preprocessed_raw.csv",
        help="Input CSV generated by preprocess_raw.py",
    )
    parser.add_argument(
        "--output-csv",
        type=str,
        default="preprocessed_thumb.csv",
        help="Output thumb CSV for train_forward_thumb.py / train_inverse_thumb.py",
    )
    parser.add_argument(
        "--thumb-only",
        action="store_true",
        help="Keep only rows where active_finger == thumb",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    m_source_cols = thumb_source_columns(args.hand)
    input_path = Path(args.input_csv)
    output_path = Path(args.output_csv)

    if not input_path.exists():
        raise FileNotFoundError(f"Input CSV not found: {input_path}")

    output_path.parent.mkdir(parents=True, exist_ok=True)

    rows_written = 0
    with input_path.open("r", newline="", encoding="utf-8") as src, output_path.open(
        "w", newline="", encoding="utf-8"
    ) as dst:
        reader = csv.DictReader(src)
        required = META_COLS + Q_SOURCE_COLS + m_source_cols
        missing = [col for col in required if col not in (reader.fieldnames or [])]
        if missing:
            raise ValueError(f"Missing required columns in {input_path}: {missing}")

        fieldnames = META_COLS + Q_SOURCE_COLS + M_TARGET_COLS
        writer = csv.DictWriter(dst, fieldnames=fieldnames)
        writer.writeheader()

        for row in reader:
            if args.thumb_only and row.get("active_finger") != "thumb":
                continue

            out_row = {col: row[col] for col in META_COLS}
            for col in Q_SOURCE_COLS:
                out_row[col] = row[col]
            for target_col, source_col in zip(M_TARGET_COLS, m_source_cols):
                out_row[target_col] = row[source_col]

            writer.writerow(out_row)
            rows_written += 1

    print(f"wrote {rows_written} rows to {output_path}")
    print(f"q columns: {Q_SOURCE_COLS}")
    print(f"m source columns: {m_source_cols}")
    print(f"m target columns: {M_TARGET_COLS}")


if __name__ == "__main__":
    main()
